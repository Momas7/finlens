export const MERCHANTS: readonly Merchant[] = RAW.map(([key, name, categoryKey, ...patterns]) => ({
  key,
  name,
  categoryKey,
  patterns,
}));

const INDEX = MERCHANTS.flatMap((m) => m.patterns.map((p) => ({ pattern: p, merchant: m }))).sort(
  (a, b) => b.pattern.length - a.pattern.length,
);

/** Estabelecimento pelo padrão mais longo que aparece em fronteira de palavra. */
export function matchMerchant(normalized: string): Merchant | null {
  if (!normalized) return null;
  const padded = ` ${normalized} `;
  return INDEX.find(({ pattern }) => padded.includes(` ${pattern} `))?.merchant ?? null;
}
